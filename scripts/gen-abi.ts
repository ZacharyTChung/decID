/**
 * Writes src/generated/contracts.ts from the Hardhat artifacts so the browser,
 * the server and the scripts share one ABI source. Run after `hardhat compile`
 * (npm run compile does both). With --check it fails if the file is stale.
 */
import { readFileSync, writeFileSync } from "node:fs";

const read = (name: string) =>
  JSON.parse(readFileSync(`artifacts/contracts/${name}.sol/${name}.json`, "utf8")) as { abi: unknown; bytecode: string };

const registry = read("CredentialRegistry");
const gate = read("DemoGate");
const out =
  `// GENERATED by scripts/gen-abi.ts from contracts/*.sol. Do not edit by hand.\n` +
  `export const CREDENTIAL_REGISTRY_ABI = ${JSON.stringify(registry.abi, null, 2)} as const;\n\n` +
  `export const DEMO_GATE_ABI = ${JSON.stringify(gate.abi, null, 2)} as const;\n`;

const target = "src/generated/contracts.ts";
if (process.argv.includes("--check")) {
  const current = readFileSync(target, "utf8");
  if (current !== out) {
    console.error(`${target} is stale. Run: npm run compile`);
    process.exit(1);
  }
  console.log(`${target} is up to date.`);
} else {
  writeFileSync(target, out);
  console.log(`wrote ${target}`);
}
