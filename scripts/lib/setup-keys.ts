import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { exportJWK, generateKeyPair } from "jose";
import { Wallet } from "ethers";
import { CREDENTIAL_TYPE, SCHEMA_ID } from "../../src/lib/shared/constants";
import { deriveDidKeyFromJwk, type Ed25519PublicJwk } from "../../src/lib/server/did/did-key";
import { DEV_ROLES, devWallet } from "./dev-accounts";

export interface SetupOptions {
  envFile: string;
  trustFile: string;
  appOrigin: string;
  rpcUrl: string;
  force?: boolean;
  extraEnv?: Record<string, string>;
}

export interface SetupResult {
  issuerDid: string;
  issuerKid: string;
  issuerEvmAddress: string;
  created: boolean;
}

/**
 * Generates the issuer's two development signing keys into a git-ignored env
 * file (mode 0600) and writes the matching public trust policy.
 *
 * - Ed25519 credential key → did:key (issuer DID), signs vc+jwt credentials.
 * - secp256k1 EVM attestation key → authorized in CredentialRegistry, signs
 *   EIP-712 registration authorizations and sends revocations.
 *
 * Re-running without --force keeps existing keys, because new keys would
 * invalidate every credential issued so far.
 */
export async function setupKeys(opts: SetupOptions): Promise<SetupResult> {
  let created = false;
  if (!existsSync(opts.envFile) || opts.force) {
    const { privateKey } = await generateKeyPair("Ed25519", { extractable: true });
    const privateJwk = await exportJWK(privateKey);
    const evm = Wallet.createRandom();
    const lines = [
      "# GENERATED by `npm run setup`. LOCAL DEVELOPMENT SECRETS. Never commit, never reuse elsewhere.",
      "# Server-only: none of these use the NEXT_PUBLIC_ prefix, so Next.js never bundles them for the browser.",
      `APP_ORIGIN=${opts.appOrigin}`,
      `RPC_URL=${opts.rpcUrl}`,
      `ISSUER_CREDENTIAL_PRIVATE_JWK=${JSON.stringify({ kty: privateJwk.kty, crv: privateJwk.crv, x: privateJwk.x, d: privateJwk.d })}`,
      `ISSUER_EVM_PRIVATE_KEY=${evm.privateKey}`,
      `# Wallets allowed to sign in to the issuer console (Hardhat dev account #${DEV_ROLES.issuerOperator}).`,
      `ISSUER_OPERATOR_ADDRESSES=${devWallet(DEV_ROLES.issuerOperator).address}`,
      ...Object.entries(opts.extraEnv ?? {}).map(([k, v]) => `${k}=${v}`),
      "",
    ];
    mkdirSync(path.dirname(opts.envFile), { recursive: true });
    writeFileSync(opts.envFile, lines.join("\n"), { mode: 0o600 });
    chmodSync(opts.envFile, 0o600);
    created = true;
  }

  const env = parseEnvFile(opts.envFile);
  const priv = JSON.parse(env.ISSUER_CREDENTIAL_PRIVATE_JWK!) as Ed25519PublicJwk & { d: string };
  const publicJwk: Ed25519PublicJwk = { kty: "OKP", crv: "Ed25519", x: priv.x };
  const { did, kid } = await deriveDidKeyFromJwk(publicJwk);
  const issuerEvmAddress = new Wallet(env.ISSUER_EVM_PRIVATE_KEY!).address;

  const trust = {
    version: 1,
    issuers: [
      {
        name: "Simulated Identity Office (local development only)",
        did,
        kid,
        publicKeyJwk: publicJwk,
        evmAttestationSigner: issuerEvmAddress,
        credentialTypes: [CREDENTIAL_TYPE],
        schemaIds: [SCHEMA_ID],
      },
    ],
  };
  mkdirSync(path.dirname(opts.trustFile), { recursive: true });
  writeFileSync(opts.trustFile, JSON.stringify(trust, null, 2) + "\n");
  return { issuerDid: did, issuerKid: kid, issuerEvmAddress, created };
}

export function parseEnvFile(file: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const line of readFileSync(file, "utf8").split("\n")) {
    const m = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
    if (m) out[m[1]!] = m[2]!;
  }
  return out;
}
